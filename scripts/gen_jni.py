#!/usr/bin/env python3
"""Generate droid/include/jni.h and droid/jni_table.c.

The JNINativeInterface layout must match the JNI spec slot-for-slot; generating
it from one ordered list avoids hand-ordering mistakes. All Call*/Get*/Set*
families are implemented generically on top of a handful of core functions in
jvm.c (jvm_invoke, jvm_field_get/set, ...).
"""
import os

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
TYPES = [("Object", "jobject", "l"), ("Boolean", "jboolean", "z"), ("Byte", "jbyte", "b"), ("Char", "jchar", "c"),
         ("Short", "jshort", "s"), ("Int", "jint", "i"), ("Long", "jlong", "j"), ("Float", "jfloat", "f"),
         ("Double", "jdouble", "d")]
PRIMS = TYPES[1:]
CALL_TYPES = TYPES + [("Void", "void", None)]


def slots():
    s = ["reserved0", "reserved1", "reserved2", "reserved3"]
    s += ["GetVersion", "DefineClass", "FindClass", "FromReflectedMethod", "FromReflectedField", "ToReflectedMethod",
          "GetSuperclass", "IsAssignableFrom", "ToReflectedField", "Throw", "ThrowNew", "ExceptionOccurred",
          "ExceptionDescribe", "ExceptionClear", "FatalError", "PushLocalFrame", "PopLocalFrame", "NewGlobalRef",
          "DeleteGlobalRef", "DeleteLocalRef", "IsSameObject", "NewLocalRef", "EnsureLocalCapacity", "AllocObject",
          "NewObject", "NewObjectV", "NewObjectA", "GetObjectClass", "IsInstanceOf", "GetMethodID"]
    for n, _, _ in CALL_TYPES:
        s += [f"Call{n}Method", f"Call{n}MethodV", f"Call{n}MethodA"]
    for n, _, _ in CALL_TYPES:
        s += [f"CallNonvirtual{n}Method", f"CallNonvirtual{n}MethodV", f"CallNonvirtual{n}MethodA"]
    s += ["GetFieldID"]
    s += [f"Get{n}Field" for n, _, _ in TYPES]
    s += [f"Set{n}Field" for n, _, _ in TYPES]
    s += ["GetStaticMethodID"]
    for n, _, _ in CALL_TYPES:
        s += [f"CallStatic{n}Method", f"CallStatic{n}MethodV", f"CallStatic{n}MethodA"]
    s += ["GetStaticFieldID"]
    s += [f"GetStatic{n}Field" for n, _, _ in TYPES]
    s += [f"SetStatic{n}Field" for n, _, _ in TYPES]
    s += ["NewString", "GetStringLength", "GetStringChars", "ReleaseStringChars", "NewStringUTF", "GetStringUTFLength",
          "GetStringUTFChars", "ReleaseStringUTFChars", "GetArrayLength", "NewObjectArray", "GetObjectArrayElement",
          "SetObjectArrayElement"]
    s += [f"New{n}Array" for n, _, _ in PRIMS]
    s += [f"Get{n}ArrayElements" for n, _, _ in PRIMS]
    s += [f"Release{n}ArrayElements" for n, _, _ in PRIMS]
    s += [f"Get{n}ArrayRegion" for n, _, _ in PRIMS]
    s += [f"Set{n}ArrayRegion" for n, _, _ in PRIMS]
    s += ["RegisterNatives", "UnregisterNatives", "MonitorEnter", "MonitorExit", "GetJavaVM", "GetStringRegion",
          "GetStringUTFRegion", "GetPrimitiveArrayCritical", "ReleasePrimitiveArrayCritical", "GetStringCritical",
          "ReleaseStringCritical", "NewWeakGlobalRef", "DeleteWeakGlobalRef", "ExceptionCheck", "NewDirectByteBuffer",
          "GetDirectBufferAddress", "GetDirectBufferCapacity", "GetObjectRefType"]
    return s


HEADER = r'''// GENERATED by scripts/gen_jni.py -- minimal, ABI-compatible jni.h
#pragma once
#include <stdarg.h>
#include <stdint.h>

typedef uint8_t jboolean;
typedef int8_t jbyte;
typedef uint16_t jchar;
typedef int16_t jshort;
typedef int32_t jint;
typedef int64_t jlong;
typedef float jfloat;
typedef double jdouble;
typedef jint jsize;
typedef void *jobject;
typedef jobject jclass, jstring, jarray, jobjectArray, jbooleanArray, jbyteArray, jcharArray, jshortArray,
    jintArray, jlongArray, jfloatArray, jdoubleArray, jthrowable, jweak;
typedef struct _jfieldID *jfieldID;
typedef struct _jmethodID *jmethodID;
typedef union jvalue { jboolean z; jbyte b; jchar c; jshort s; jint i; jlong j; jfloat f; jdouble d; jobject l; } jvalue;
typedef enum { JNIInvalidRefType = 0, JNILocalRefType = 1, JNIGlobalRefType = 2, JNIWeakGlobalRefType = 3 } jobjectRefType;
typedef struct { const char *name; const char *signature; void *fnPtr; } JNINativeMethod;

#define JNI_FALSE 0
#define JNI_TRUE 1
#define JNI_OK 0
#define JNI_ERR (-1)
#define JNI_EDETACHED (-2)
#define JNI_VERSION_1_6 0x00010006

struct JNINativeInterface;
struct JNIInvokeInterface;
typedef const struct JNINativeInterface *JNIEnv;
typedef const struct JNIInvokeInterface *JavaVM;

struct JNIInvokeInterface {
    void *reserved0, *reserved1, *reserved2;
    jint (*DestroyJavaVM)(JavaVM *);
    jint (*AttachCurrentThread)(JavaVM *, JNIEnv **, void *);
    jint (*DetachCurrentThread)(JavaVM *);
    jint (*GetEnv)(JavaVM *, void **, jint);
    jint (*AttachCurrentThreadAsDaemon)(JavaVM *, JNIEnv **, void *);
};

struct JNINativeInterface {
'''


def main():
    s = slots()
    h = [HEADER]
    for name in s:
        h.append(f"    void *{name};" if name.startswith("reserved") else f"    void *{name};")
    h.append("};")
    h.append(f"#define WWD_JNI_SLOTS {len(s)}")
    open(os.path.join(ROOT, "droid", "include", "jni.h"), "w").write("\n".join(h) + "\n")

    c = ["// GENERATED by scripts/gen_jni.py", '#include "jvm.h"', ""]
    impl = {}

    def emit(name, ret, params, body):
        c.append(f"static {ret} j_{name}({params}) {{ {body} }}")
        impl[name] = f"j_{name}"

    for n, ct, f in CALL_TYPES:
        conv = "" if f is None else f"return ({ct})r.{f};"
        rv = "void" if f is None else ct
        for kind, objp, clsx in (("", "jobject o", "NULL"), ("Nonvirtual", "jobject o, jclass k", "k"), ("Static", "jclass k", "k")):
            obj = "NULL" if kind == "Static" else "o"
            pre = "jvalue r = "
            emit(f"Call{kind}{n}Method", rv, f"JNIEnv *e, {objp}, jmethodID m, ...",
                 f"va_list ap; va_start(ap, m); jvalue a[32]; jvm_args_from_va(m, ap, a); va_end(ap); {pre}jvm_invoke(e, {obj}, {clsx}, m, a); (void)r; {conv}")
            emit(f"Call{kind}{n}MethodV", rv, f"JNIEnv *e, {objp}, jmethodID m, va_list ap",
                 f"jvalue a[32]; jvm_args_from_va(m, ap, a); {pre}jvm_invoke(e, {obj}, {clsx}, m, a); (void)r; {conv}")
            emit(f"Call{kind}{n}MethodA", rv, f"JNIEnv *e, {objp}, jmethodID m, const jvalue *a",
                 f"{pre}jvm_invoke(e, {obj}, {clsx}, m, a); (void)r; {conv}")
    for n, ct, f in TYPES:
        emit(f"Get{n}Field", ct, "JNIEnv *e, jobject o, jfieldID fid", f"(void)e; return ({ct})jvm_field_get(o, fid).{f};")
        emit(f"Set{n}Field", "void", f"JNIEnv *e, jobject o, jfieldID fid, {ct} v", f"(void)e; jvalue x; x.j = 0; x.{f} = v; jvm_field_set(o, fid, x);")
        emit(f"GetStatic{n}Field", ct, "JNIEnv *e, jclass k, jfieldID fid", f"(void)e; return ({ct})jvm_field_get(k, fid).{f};")
        emit(f"SetStatic{n}Field", "void", f"JNIEnv *e, jclass k, jfieldID fid, {ct} v", f"(void)e; jvalue x; x.j = 0; x.{f} = v; jvm_field_set(k, fid, x);")
    for n, ct, f in PRIMS:
        a = f"{ct}Array"
        emit(f"New{n}Array", "jarray", "JNIEnv *e, jsize len", f"(void)e; return jvm_new_array('{f}', len);")
        emit(f"Get{n}ArrayElements", f"{ct} *", "JNIEnv *e, jarray arr, jboolean *copy", f"(void)e; if (copy) *copy = 0; return ({ct} *)jvm_array_data(arr);")
        emit(f"Release{n}ArrayElements", "void", f"JNIEnv *e, jarray arr, {ct} *p, jint mode", "(void)e; (void)arr; (void)p; (void)mode;")
        emit(f"Get{n}ArrayRegion", "void", f"JNIEnv *e, jarray arr, jsize s, jsize l, {ct} *buf",
             f"(void)e; memcpy(buf, ({ct} *)jvm_array_data(arr) + s, (size_t)l * sizeof({ct}));")
        emit(f"Set{n}ArrayRegion", "void", f"JNIEnv *e, jarray arr, jsize s, jsize l, const {ct} *buf",
             f"(void)e; memcpy(({ct} *)jvm_array_data(arr) + s, buf, (size_t)l * sizeof({ct}));")
    emit("NewObject", "jobject", "JNIEnv *e, jclass k, jmethodID m, ...",
         "va_list ap; va_start(ap, m); jvalue a[32]; jvm_args_from_va(m, ap, a); va_end(ap); return jvm_new_object(e, k, m, a);")
    emit("NewObjectV", "jobject", "JNIEnv *e, jclass k, jmethodID m, va_list ap",
         "jvalue a[32]; jvm_args_from_va(m, ap, a); return jvm_new_object(e, k, m, a);")
    emit("NewObjectA", "jobject", "JNIEnv *e, jclass k, jmethodID m, const jvalue *a", "return jvm_new_object(e, k, m, a);")

    c.append("")
    c.append("void *wwd_jni_table[WWD_JNI_SLOTS];")
    c.append("void wwd_jni_fill_generated(void) {")
    for i, name in enumerate(s):
        if name in impl:
            c.append(f"    wwd_jni_table[{i}] = (void *){impl[name]};")
    c.append("}")
    c.append("int wwd_jni_slot(const char *name) {")
    c.append("    static const char *const names[] = {" + ", ".join(f'"{n}"' for n in s) + "};")
    c.append("    for (int i = 0; i < WWD_JNI_SLOTS; i++) if (!strcmp(names[i], name)) return i;")
    c.append("    return -1;")
    c.append("}")
    c.append("const char *wwd_jni_slot_name(int i) {")
    c.append("    static const char *const names[] = {" + ", ".join(f'"{n}"' for n in s) + "};")
    c.append("    return (i >= 0 && i < WWD_JNI_SLOTS) ? names[i] : \"?\";")
    c.append("}")
    open(os.path.join(ROOT, "droid", "jni_table.c"), "w").write("\n".join(c) + "\n")
    print(len(s), "JNI slots")


if __name__ == "__main__":
    main()
