#!/usr/bin/env python3
"""Generate droid/libGLESv3.c: a query-only GLES 3.2 for device detection.

Answers capability queries like a modern mobile GPU (GL ES 3.2, ASTC + ETC2)
and accepts every other entry point libUnreal imports as a no-op. Rendering
goes through Vulkan, so nothing here draws.
"""
import os

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
IMPORTS = os.path.join(ROOT, "games", "overgeared", "og_imp.txt")

HAND = r'''// GENERATED by scripts/gen_gles.py
// libGLESv3 for wwd: answers capability queries like a modern mobile GPU
// (GL ES 3.2, ASTC/ETC2) and accepts every other call as a no-op.
#include <stdint.h>
#include <stddef.h>
#include <string.h>
#include <stdlib.h>

static const char *EXT[] = {"GL_KHR_texture_compression_astc_ldr", "GL_KHR_texture_compression_astc_hdr",
    "GL_OES_texture_compression_astc", "GL_EXT_texture_compression_astc_decode_mode", "GL_OES_compressed_ETC1_RGB8_texture",
    "GL_EXT_color_buffer_float", "GL_EXT_color_buffer_half_float", "GL_EXT_texture_buffer", "GL_OES_texture_buffer",
    "GL_EXT_geometry_shader", "GL_EXT_tessellation_shader", "GL_EXT_shader_framebuffer_fetch", "GL_EXT_disjoint_timer_query",
    "GL_OES_EGL_image", "GL_OES_EGL_image_external", "GL_OES_EGL_image_external_essl3", "GL_EXT_texture_filter_anisotropic",
    "GL_EXT_debug_marker", "GL_KHR_debug", "GL_OES_vertex_array_object", "GL_EXT_shader_io_blocks",
    "GL_ANDROID_extension_pack_es31a", "GL_EXT_texture_cube_map_array", "GL_EXT_copy_image", "GL_EXT_draw_buffers_indexed",
    "GL_EXT_multisampled_render_to_texture", "GL_OES_depth24", "GL_OES_packed_depth_stencil", "GL_OES_rgb8_rgba8",
    "GL_EXT_texture_format_BGRA8888", NULL};

static const char *ext_joined(void) {
    static char buf[4096];
    if (!buf[0])
        for (int i = 0; EXT[i]; i++) {
            strcat(buf, EXT[i]);
            strcat(buf, " ");
        }
    return buf;
}

static int next_name = 1;

const unsigned char *glGetString(unsigned name) {
    switch (name) {
    case 0x1F00: return (const unsigned char *)"Qualcomm";                          // GL_VENDOR
    case 0x1F01: return (const unsigned char *)"Adreno (TM) 740";                   // GL_RENDERER
    case 0x1F02: return (const unsigned char *)"OpenGL ES 3.2 V@0676.42 (GIT@wwd)";  // GL_VERSION
    case 0x8B8C: return (const unsigned char *)"OpenGL ES GLSL ES 3.20";             // SHADING_LANGUAGE_VERSION
    case 0x1F03: return (const unsigned char *)ext_joined();                         // GL_EXTENSIONS
    }
    return (const unsigned char *)"";
}

const unsigned char *glGetStringi(unsigned name, unsigned i) {
    int n = 0;
    while (EXT[n]) n++;
    return (name == 0x1F03 && (int)i < n) ? (const unsigned char *)EXT[i] : NULL;
}

static long iv(unsigned p) {
    switch (p) {
    case 0x821B: return 3;                                    // MAJOR_VERSION
    case 0x821C: return 2;                                    // MINOR_VERSION
    case 0x821D: { int n = 0; while (EXT[n]) n++; return n; } // NUM_EXTENSIONS
    case 0x0D33: case 0x851C: case 0x84E8: case 0x0D3A: return 16384;
    case 0x8073: case 0x88FF: return 2048;
    case 0x8D57: return 4;
    case 0x8869: case 0x8B4C: case 0x8872: case 0x9122: return 16;
    case 0x8DFB: case 0x8DFD: case 0x91BE: case 0x91BF: case 0x90EB: return 1024;
    case 0x8B4D: return 96;
    case 0x8824: case 0x8CDF: return 8;
    case 0x8A2F: return 84;
    case 0x8A30: return 65536;
    case 0x8A34: return 4;
    case 0x86A2: return 18;                                   // NUM_COMPRESSED_TEXTURE_FORMATS
    case 0x0D50: case 0x0D52: case 0x0D53: case 0x0D54: case 0x0D55: case 0x0D57: return 8;
    case 0x0D56: return 24;
    case 0x8E89: return 65535;
    }
    return 0;
}

void glGetIntegerv(unsigned p, int *v) {
    if (!v) return;
    if (p == 0x86A3) { // COMPRESSED_TEXTURE_FORMATS: ASTC 4x4..12x12 + ETC2
        static const int f[] = {0x93B0, 0x93B1, 0x93B2, 0x93B3, 0x93B4, 0x93B5, 0x93B6, 0x93B7, 0x93B8,
                                0x93B9, 0x93BA, 0x93BB, 0x93BC, 0x93BD, 0x9274, 0x9278, 0x9275, 0x9279};
        memcpy(v, f, sizeof f);
        return;
    }
    *v = (int)iv(p);
}
void glGetInteger64v(unsigned p, int64_t *v) { if (v) *v = iv(p); }
void glGetBooleanv(unsigned p, unsigned char *v) { if (v) *v = (unsigned char)(iv(p) != 0); }
void glGetFloatv(unsigned p, float *v) { if (v) *v = p == 0x84FF ? 16.0f : (float)iv(p); }
unsigned glGetError(void) { return 0; }
void glGetShaderPrecisionFormat(unsigned s, unsigned t, int *range, int *prec) {
    (void)s;
    if (range) { range[0] = 127; range[1] = 127; }
    if (prec) *prec = (t >= 0x8DF3) ? 0 : 23;
}
unsigned glCreateShader(unsigned t) { (void)t; return (unsigned)next_name++; }
unsigned glCreateProgram(void) { return (unsigned)next_name++; }
void glGetShaderiv(unsigned s, unsigned p, int *v) { (void)s; if (v) *v = (p == 0x8B81) ? 1 : 0; }
void glGetProgramiv(unsigned s, unsigned p, int *v) { (void)s; if (v) *v = (p == 0x8B82) ? 1 : 0; }
void *glFenceSync(unsigned c, unsigned f) { (void)c; (void)f; return (void *)1; }
unsigned glClientWaitSync(void *s, unsigned f, uint64_t t) { (void)s; (void)f; (void)t; return 0x911A; }
void *glMapBufferRange(unsigned t, intptr_t o, intptr_t l, unsigned a) { (void)t; (void)o; (void)a; return l > 0 ? calloc(1, (size_t)l) : NULL; }
int glGetUniformLocation(unsigned p, const char *n) { (void)p; (void)n; return -1; }
unsigned glGetUniformBlockIndex(unsigned p, const char *n) { (void)p; (void)n; return 0xFFFFFFFFu; }
unsigned glGetProgramResourceIndex(unsigned p, unsigned i, const char *n) { (void)p; (void)i; (void)n; return 0xFFFFFFFFu; }
unsigned char glIsEnabled(unsigned c) { (void)c; return 0; }
unsigned char glIsTexture(unsigned t) { (void)t; return 1; }
void glGetQueryObjectuiv(unsigned q, unsigned p, unsigned *v) { (void)q; (void)p; if (v) *v = 1; }
'''

SPECIAL = {"glGetString", "glGetError", "glGetIntegerv", "glGetStringi", "glGetInteger64v", "glGetBooleanv",
           "glGetShaderPrecisionFormat", "glCreateShader", "glCreateProgram", "glGetShaderiv", "glGetProgramiv",
           "glFenceSync", "glClientWaitSync", "glMapBufferRange", "glGetUniformLocation", "glGetUniformBlockIndex",
           "glGetProgramResourceIndex", "glGetFloatv", "glIsEnabled", "glIsTexture", "glGetQueryObjectuiv"}


def main():
    imps = [l.strip() for l in open(IMPORTS) if l.startswith("   ")]
    gl = sorted({s for s in imps if s.startswith("gl") and s[2:3].isupper()})
    out = [HAND]
    for s in gl:
        if s not in SPECIAL:
            out.append(f"intptr_t {s}(void) {{ return 0; }}")
    open(os.path.join(ROOT, "droid", "libGLESv3.c"), "w").write("\n".join(out) + "\n")
    print(len(gl), "GL entry points")


if __name__ == "__main__":
    main()
