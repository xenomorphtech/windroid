#!/usr/bin/env python3
"""Generate the Vulkan guest thunk library and the host dispatch table from vk.xml.

Outputs:
  thunks/vulkan/vk_stubs.c                 aarch64 guest stubs (one per command)
  crates/wwd-linux/src/thunk/vk_table.rs   host table: name, param shape

Each guest stub is   mov x8, #<id> ; svc #0x5757 ; ret
The host reads args per AAPCS64 and re-issues the call per Win64.
"""
import os, sys, urllib.request
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
XML = os.path.join(ROOT, "tools", "vk.xml")
URL = "https://raw.githubusercontent.com/KhronosGroup/Vulkan-Docs/v1.4.330/xml/vk.xml"

# Commands implemented by hand on the guest side (not plain thunks).
GUEST_IMPL = {"vkGetInstanceProcAddr", "vkGetDeviceProcAddr"}


def load():
    if not os.path.exists(XML):
        os.makedirs(os.path.dirname(XML), exist_ok=True)
        print("fetch", URL, file=sys.stderr)
        urllib.request.urlretrieve(URL, XML)
    return ET.parse(XML).getroot()


def main():
    reg = load()
    cmds, aliases = {}, {}
    for c in reg.find("commands").findall("command"):
        if c.get("api") and "vulkan" not in c.get("api").split(","):
            continue  # vulkansc-only variants
        if c.get("alias"):
            aliases[c.get("name")] = c.get("alias")
            continue
        proto = c.find("proto")
        name = proto.find("name").text
        params = []
        for p in c.findall("param"):
            if p.get("api") and "vulkan" not in p.get("api").split(","):
                continue
            ptype = p.find("type").text
            text = "".join(p.itertext())
            is_ptr = "*" in text or "[" in text
            params.append((ptype, is_ptr))
        cmds[name] = params
    for a, target in aliases.items():
        if target in cmds:
            cmds[a] = cmds[target]
    names = sorted(n for n in cmds if n not in GUEST_IMPL)

    # id 0 is reserved for the "has" query used by the guest-side GetProcAddr
    stub_lines = ["// GENERATED by scripts/gen_vulkan_thunks.py -- do not edit", "#include \"vk_thunk.h\"", ""]
    table = ["// GENERATED by scripts/gen_vulkan_thunks.py -- do not edit", "",
             "pub struct VkCmd { pub name: &'static str, pub nparams: u8, pub float_mask: u32, pub alloc_mask: u32 }", "",
             "pub static VK_CMDS: &[VkCmd] = &["]
    table.append('    VkCmd { name: "", nparams: 0, float_mask: 0, alloc_mask: 0 },')
    procs = []
    for i, n in enumerate(names, start=1):
        params = cmds[n]
        fm = sum(1 << k for k, (t, ptr) in enumerate(params) if t in ("float", "double") and not ptr)
        am = sum(1 << k for k, (t, ptr) in enumerate(params) if t == "VkAllocationCallbacks")
        table.append(f'    VkCmd {{ name: "{n}", nparams: {len(params)}, float_mask: {fm:#x}, alloc_mask: {am:#x} }},')
        stub_lines.append(f"WWD_THUNK({n}, {i})")
        procs.append(n)
    table.append("];")
    stub_lines.append("")
    stub_lines.append("const struct wwd_proc wwd_vk_procs[] = {")
    for n in sorted(procs + list(GUEST_IMPL)):
        stub_lines.append(f'    {{"{n}", (void *){n}}},')
    stub_lines.append("};")
    stub_lines.append(f"const unsigned wwd_vk_nprocs = {len(procs) + len(GUEST_IMPL)};")

    out_c = os.path.join(ROOT, "thunks", "vulkan", "vk_stubs.c")
    out_rs = os.path.join(ROOT, "crates", "wwd-linux", "src", "thunk", "vk_table.rs")
    os.makedirs(os.path.dirname(out_c), exist_ok=True)
    os.makedirs(os.path.dirname(out_rs), exist_ok=True)
    open(out_c, "w").write("\n".join(stub_lines) + "\n")
    open(out_rs, "w").write("\n".join(table) + "\n")
    print(f"{len(procs)} thunked commands")


if __name__ == "__main__":
    main()
